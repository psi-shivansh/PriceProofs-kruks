/**
 * Helper to keep Indian return-policy boilerplate concise & consistent while preserving
 * store-specific nuance (Service Center DOA vs Open-Box OTP vs Direct Brand Refund).
 */
function makeServiceCenterPolicy(
  storeName: string,
  sourceUrl: string,
  summary: string,
  score: number,
  windowDays = 7
): StoreListing['returnPolicy'] {
  return {
    policyFound: true,
    windowLabel: `${windowDays}d Service Center Replacement`,
    windowDays,
    windowSignal: 'warn',
    returnShippingLabel: 'Customer visits authorized brand service center',
    returnShippingSignal: 'warn',
    refundMethod: 'Replacement Only (DOA Certificate Required)',
    refundMethodSignal: 'bad',
    refundSpeed: '7–10 business days',
    refundSpeedSignal: 'warn',
    restockingFeeLabel: '₹0',
    restockingFeePercent: 0,
    restockingSignal: 'good',
    exchangeAllowed: 'DOA Replacement Only',
    exchangeSignal: 'warn',
    conditions: `${storeName} requires an official brand Dead-on-Arrival (DOA) job sheet before approving replacement.`,
    plainEnglishSummary: summary,
    policyScore: score,
    sourceUrl,
    timeline: [
      { step: 'Report Issue', duration: `Day 0–${windowDays}`, detail: 'Log defect ticket in order history.' },
      { step: 'Brand Service Visit', duration: 'Day 2–5', detail: 'Authorized center verifies hardware fault & issues DOA.' },
      { step: 'Replacement', duration: 'Day 7–10', detail: 'Sealed replacement unit dispatched.' },
    ],
  };
}

